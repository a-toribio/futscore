import { describe, expect, it } from 'vitest'
import { translatePosition } from '@/lib/positions'

describe('translatePosition', () => {
  it('traduce porteros correctamente', () => {
    expect(translatePosition('G').code).toBe('POR')
    expect(translatePosition('GK').code).toBe('POR')
    expect(translatePosition('Goalkeeper').code).toBe('POR')
    expect(translatePosition('Goal Keeper').code).toBe('POR')
    expect(translatePosition('Portero').code).toBe('POR')
    expect(translatePosition('Arquero').code).toBe('POR')
    expect(translatePosition('GK').label).toBe('Portero')
  })

  it('traduce defensas correctamente sin colisionar con centrocampistas', () => {
    expect(translatePosition('CD-L').code).toBe('DEF')
    expect(translatePosition('CD-R').code).toBe('DEF')
    expect(translatePosition('CB').code).toBe('DEF')
    expect(translatePosition('CB-L').code).toBe('DEF')
    expect(translatePosition('LB').code).toBe('DEF')
    expect(translatePosition('RB').code).toBe('DEF')
    expect(translatePosition('LWB').code).toBe('DEF')
    expect(translatePosition('RWB').code).toBe('DEF')
    expect(translatePosition('Center Left Defender').code).toBe('DEF')
    expect(translatePosition('Center Right Defender').code).toBe('DEF')
    expect(translatePosition('Left Back').code).toBe('DEF')
    expect(translatePosition('Right Back').code).toBe('DEF')
    expect(translatePosition('Full-Back').code).toBe('DEF')
    expect(translatePosition('Defender').code).toBe('DEF')
    expect(translatePosition('Defensa').label).toBe('Defensa')
  })

  it('traduce centrocampistas correctamente (incluyendo CDM y Attacking Midfielder)', () => {
    expect(translatePosition('AM').code).toBe('MED')
    expect(translatePosition('AM-L').code).toBe('MED')
    expect(translatePosition('AM-R').code).toBe('MED')
    expect(translatePosition('CM').code).toBe('MED')
    expect(translatePosition('CM-L').code).toBe('MED')
    expect(translatePosition('LM').code).toBe('MED')
    expect(translatePosition('RM').code).toBe('MED')
    expect(translatePosition('DM').code).toBe('MED')
    expect(translatePosition('CDM').code).toBe('MED')
    expect(translatePosition('CAM').code).toBe('MED')
    expect(translatePosition('Attacking Midfielder').code).toBe('MED')
    expect(translatePosition('Attacking Midfielder Left').code).toBe('MED')
    expect(translatePosition('Attacking Midfielder Right').code).toBe('MED')
    expect(translatePosition('Central Midfielder').code).toBe('MED')
    expect(translatePosition('Defensive Midfielder').code).toBe('MED')
    expect(translatePosition('Midfielder').label).toBe('Centrocampista')
  })

  it('traduce delanteros correctamente', () => {
    expect(translatePosition('F').code).toBe('DEL')
    expect(translatePosition('CF').code).toBe('DEL')
    expect(translatePosition('ST').code).toBe('DEL')
    expect(translatePosition('SS').code).toBe('DEL')
    expect(translatePosition('LW').code).toBe('DEL')
    expect(translatePosition('RW').code).toBe('DEL')
    expect(translatePosition('Forward').code).toBe('DEL')
    expect(translatePosition('Centre-Forward').code).toBe('DEL')
    expect(translatePosition('Striker').code).toBe('DEL')
    expect(translatePosition('Winger').code).toBe('DEL')
    expect(translatePosition('Left Winger').code).toBe('DEL')
    expect(translatePosition('Right Winger').code).toBe('DEL')
    expect(translatePosition('Delantero').label).toBe('Delantero')
  })

  it('traduce suplentes y valores vacíos o desconocidos', () => {
    expect(translatePosition('SUB').code).toBe('SUP')
    expect(translatePosition('Substitute').code).toBe('SUP')
    expect(translatePosition('Reserves').code).toBe('SUP')
    expect(translatePosition('Suplente').label).toBe('Suplente')
    expect(translatePosition('').code).toBe('SUP')
    expect(translatePosition(undefined).code).toBe('SUP')
    expect(translatePosition('UNKNOWN_POS').code).toBe('SUP')
  })
})
